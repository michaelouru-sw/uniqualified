namespace local_courseaudit;

/**
 * Surfaces Moodle core's own Analytics API predictions (the "Machine Learning Backend" feature -
 * Site administration > Analytics) on the course audit dashboard, rather than leaving them stuck
 * on Moodle's separate /report/insights/ page. No new dependency: this reads whatever core's
 * analytics_predictions table already has, generated by whichever predictions processor the site
 * has configured (the bundled static PHP predictor, or the separate Python mlbackend service).
 *
 * Two different retrieval strategies are used deliberately, not for consistency's own sake:
 *
 * - Course-level targets (e.g. "Courses at risk of not starting") use \core\analytics\analyser\
 *   \core\analytics\analyser\site_courses (course/classes/analytics/analyser/../lib/classes/
 *   analytics/analyser/courses.php), whose get_all_samples() maps sampleid directly to courseid
 *   1:1 ("Just one sample per analysable") - confirmed by reading that analyser's source, not
 *   assumed. That makes a direct SQL query against analytics_predictions safe and cheap across
 *   every course at once.
 * - Student-level targets (e.g. "Students at risk of dropping out") use a course_enrolments-based
 *   analyser where sampleid is an internal per-enrolment id with no simple public formula. Rather
 *   than reverse-engineer that encoding, this goes through Moodle's own supported
 *   \core_analytics\model::get_predictions() API, which resolves sample data (including the
 *   enrolled \stdClass $user) via the analyser itself - correct regardless of how the analyser
 *   encodes sample ids internally, and forward-compatible if core ever changes that encoding.
 *
 * @package    local_courseaudit
 * @copyright  2026
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class ml_insights {

    /** @var string Course-level target: "Courses at risk of not starting" (no recent teaching activity). */
    const TARGET_COURSE_AT_RISK = '\core_course\analytics\target\no_teaching';

    /** @var string Student-level target: "Students at risk of dropping out". */
    const TARGET_STUDENT_DROPOUT = '\core_course\analytics\target\course_dropout';

    /**
     * Whether core's Analytics API classes are present at all - true on every supported Moodle
     * version this plugin targets, but checked defensively rather than assumed, since this whole
     * class is optional/best-effort: the rest of the dashboard must keep working even if
     * analytics is unavailable for any reason.
     *
     * @return bool
     */
    public static function analytics_available(): bool {
        return class_exists('\core_analytics\manager');
    }

    /**
     * One row per target this class knows how to surface, describing whether it's actually usable
     * right now - so the dashboard can show an honest "not set up yet" state instead of silently
     * displaying all-zero counts that look like "checked, no risk" rather than "not analysed".
     *
     * @return array [target => ['exists' => bool, 'enabled' => bool, 'trained' => bool,
     *                            'haspredictions' => bool, 'name' => string]]
     */
    public static function model_summary(): array {
        global $DB;

        $targets = [self::TARGET_COURSE_AT_RISK, self::TARGET_STUDENT_DROPOUT];
        $summary = [];
        foreach ($targets as $target) {
            $model = $DB->get_record('analytics_models', ['target' => $target]);
            $name = class_exists($target) ? (string) $target::get_name() : $target;
            if (!$model) {
                $summary[$target] = [
                    'exists' => false, 'enabled' => false, 'trained' => false,
                    'haspredictions' => false, 'name' => $name,
                ];
                continue;
            }
            $haspredictions = $DB->record_exists('analytics_predictions', ['modelid' => $model->id]);
            $summary[$target] = [
                'exists' => true,
                'enabled' => (bool) $model->enabled,
                'trained' => (bool) $model->trained,
                'haspredictions' => $haspredictions,
                'name' => $name,
            ];
        }
        return $summary;
    }

    /**
     * Whether there is at least one target that's enabled, trained, and has generated predictions
     * - used to decide whether to show the ML section on the dashboard at all.
     *
     * @return bool
     */
    public static function has_any_usable_predictions(): bool {
        foreach (self::model_summary() as $info) {
            if ($info['enabled'] && $info['trained'] && $info['haspredictions']) {
                return true;
            }
        }
        return false;
    }

    /**
     * Courses flagged by the "Courses at risk of not starting" (no_teaching) target - courseid =>
     * ['score' => float 0-1 confidence, 'timecreated' => int]. Only the latest rangeindex per
     * course is kept (a course can be re-analysed over time; earlier predictions are superseded).
     *
     * @param int[]|null $courseids Restrict to these courses. Null means no restriction (every
     *        flagged course site-wide). An empty (non-null) array deliberately means "restrict to
     *        nothing" and returns no results - distinct from null, so a category-scoped caller
     *        with zero courses in scope gets zero back rather than accidentally seeing every
     *        flagged course on the site.
     * @return array
     */
    public static function course_risk_flags(?array $courseids = null): array {
        global $DB;

        if (!self::analytics_available()) {
            return [];
        }
        if ($courseids !== null && empty($courseids)) {
            return [];
        }
        $model = $DB->get_record('analytics_models', ['target' => self::TARGET_COURSE_AT_RISK]);
        if (!$model || !$model->enabled || !$model->trained) {
            return [];
        }

        $params = ['modelid' => $model->id, 'coursecontextlevel' => CONTEXT_COURSE];
        $coursefilter = '';
        if ($courseids !== null) {
            list($insql, $inparams) = $DB->get_in_or_equal($courseids, SQL_PARAMS_NAMED, 'crs');
            $coursefilter = "AND ctx.instanceid $insql";
            $params = array_merge($params, $inparams);
        }

        // Keeps only the latest rangeindex per sample (course), same "supersede earlier ranges"
        // rule core's own model::get_predictions() applies - see that method's own subquery.
        $sql = "SELECT ctx.instanceid AS courseid, ap.predictionscore, ap.timecreated
                  FROM {analytics_predictions} ap
                  JOIN {context} ctx ON ctx.id = ap.contextid AND ctx.contextlevel = :coursecontextlevel
                  JOIN (
                        SELECT sampleid, MAX(rangeindex) AS rangeindex
                          FROM {analytics_predictions}
                         WHERE modelid = :modelid
                      GROUP BY sampleid
                       ) latest ON latest.sampleid = ap.sampleid AND latest.rangeindex = ap.rangeindex
                 WHERE ap.modelid = :modelid2 AND ap.prediction = 1
                       $coursefilter";
        $params['modelid2'] = $model->id;

        $rows = $DB->get_records_sql($sql, $params);
        $flags = [];
        foreach ($rows as $row) {
            $flags[(int) $row->courseid] = [
                'score' => (float) $row->predictionscore,
                'timecreated' => (int) $row->timecreated,
            ];
        }
        return $flags;
    }

    /**
     * Count of students flagged "at risk of dropping out" per course - courseid => count. Goes
     * through core's own \core_analytics\model API (see this class's docblock for why), looping
     * only over contexts that actually have predictions for this model - bounded by real data
     * volume, not every course on the site.
     *
     * @param int[]|null $courseids Restrict to these courses. Null means no restriction (every
     *        course with data, site-wide). An empty (non-null) array deliberately means "restrict
     *        to nothing" and returns no results - see course_risk_flags()'s docblock for why this
     *        distinction matters for category-scoped callers.
     * @return array
     */
    public static function student_dropout_counts(?array $courseids = null): array {
        global $DB;

        if (!self::analytics_available()) {
            return [];
        }
        if ($courseids !== null && empty($courseids)) {
            return [];
        }
        $modelrecord = $DB->get_record('analytics_models', ['target' => self::TARGET_STUDENT_DROPOUT]);
        if (!$modelrecord || !$modelrecord->enabled || !$modelrecord->trained) {
            return [];
        }

        $model = new \core_analytics\model($modelrecord);
        $counts = [];
        foreach ($model->get_predictions_contexts() as $contextrow) {
            $context = \context::instance_by_id($contextrow->contextid, IGNORE_MISSING);
            if (!$context || $context->contextlevel !== CONTEXT_COURSE) {
                continue;
            }
            $courseid = (int) $context->instanceid;
            if ($courseids !== null && !in_array($courseid, $courseids, true)) {
                continue;
            }
            list(, $predictions) = $model->get_predictions($context, false);
            if (empty($predictions)) {
                continue;
            }
            $atrisk = 0;
            foreach ($predictions as $prediction) {
                $data = $prediction->get_prediction_data();
                if ((int) $data->prediction === 1) {
                    $atrisk++;
                }
            }
            if ($atrisk > 0) {
                $counts[$courseid] = $atrisk;
            }
        }
        return $counts;
    }
}
